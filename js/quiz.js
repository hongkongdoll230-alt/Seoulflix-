let selectedCategory = "mixed";
let quizQuestions = [];
let currentQuestion = 0;
let score = 0;

const quizContainer =
    document.getElementById("quiz-container");


// =========================
// SHUFFLE
// =========================

function shuffleArray(array) {

    return array.sort(() => Math.random() - 0.5);

}


// =========================
// CATEGORY SELECTION
// =========================

function showCategorySelection() {

    quizContainer.innerHTML = `

        <div class="quiz-card">

            <h2>🎯 Choose Your Quiz</h2>

            <p>Select a category:</p>

            <div class="quiz-categories">

                <button
                    class="quiz-category"
                    onclick="startQuiz('kdrama')">
                    🎬 K-Drama
                </button>

                <button
                    class="quiz-category"
                    onclick="startQuiz('anime')">
                    🍥 Anime
                </button>

                <button
                    class="quiz-category"
                    onclick="startQuiz('mixed')">
                    🌏 Mixed
                </button>

            </div>

        </div>

    `;
}


// =========================
// CREATE QUIZ
// =========================

function createQuiz() {

    let availableQuestions;

    if (selectedCategory === "mixed") {

        availableQuestions =
            [...questions];

    } else {

        availableQuestions =
            questions.filter(
                question =>
                    question.category === selectedCategory
            );

    }

    shuffleArray(availableQuestions);

    quizQuestions =
        availableQuestions.slice(0, 5);

    quizQuestions =
        quizQuestions.map(question => {

            const answers =
                question.answers.map((answer, index) => ({
                    text: answer,
                    correct: index === question.correct
                }));

            shuffleArray(answers);

            return {
                question: question.question,
                answers: answers
            };

        });

}


// =========================
// START QUIZ
// =========================

function startQuiz(category) {

    selectedCategory = category;

    currentQuestion = 0;
    score = 0;

    createQuiz();
    showQuestion();

}


// =========================
// SHOW QUESTION
// =========================

function showQuestion() {

    const question =
        quizQuestions[currentQuestion];

    quizContainer.innerHTML = `

        <div class="quiz-card">

            <p class="quiz-progress">
                Question ${currentQuestion + 1}
                of ${quizQuestions.length}
            </p>

            <h2>${question.question}</h2>

            <div class="quiz-answers">

                ${question.answers.map((answer, index) => `

                    <button
                        class="quiz-answer"
                        onclick="checkAnswer(${index})">
                        ${answer.text}
                    </button>

                `).join("")}

            </div>

        </div>

    `;

}


// =========================
// CHECK ANSWER
// =========================

function checkAnswer(selectedAnswer) {

    const question =
        quizQuestions[currentQuestion];

    if (question.answers[selectedAnswer].correct) {
        score++;
    }

    currentQuestion++;

    if (currentQuestion < quizQuestions.length) {

        showQuestion();

    } else {

        showResult();

    }

}


// =========================
// RESULT
// =========================

function showResult() {

    quizContainer.innerHTML = `

        <div class="quiz-card">

            <h2>🎉 Quiz Complete!</h2>

            <p>
                You scored
                <strong>${score}</strong>
                out of
                <strong>${quizQuestions.length}</strong>
            </p>

            <button
                class="quiz-restart"
                onclick="restartQuiz()">
                🔄 Try Again
            </button>

            <button
                class="quiz-restart"
                onclick="showCategorySelection()">
                🎯 Change Category
            </button>

        </div>

    `;

}


// =========================
// RESTART SAME CATEGORY
// =========================

function restartQuiz() {

    currentQuestion = 0;
    score = 0;

    createQuiz();
    showQuestion();

}


// =========================
// START
// =========================

showCategorySelection();